/**
 * AI 서버 깨우기 — 첫 발화가 오래 걸리는 것을 미리 없앤다.
 *
 * 왜 만들었나(2026-08-16) — AI 가 onrender 무료 플랜이라 한동안 요청이 없으면 컨테이너가
 * 잠들었다. 깨우는 데 **40초쯤** 걸렸고 그동안 백엔드는 타임아웃으로 끊어버려서,
 * 시연 첫 발화가 거의 반드시 실패했다.
 *
 * 왜 남겨두나(2026-08-16) — AI 팀이 인스턴스를 업그레이드해서 유휴 잠들기는 없어졌다
 * (실측 /health 0.27초). 그래도 이 파일은 남긴다. **재배포 직후 첫 요청**은 유료 플랜에서도
 * 컨테이너가 새로 뜨는 시간을 그대로 먹기 때문이다. 발표 전까지 AI·BE 배포는 또 일어나고,
 * 하필 시연 직전에 배포가 나가면 같은 일이 재현된다.
 * 비용은 앱을 열 때 GET 한 번 — 보험료로 싸다.
 *
 * 중요한 것: 그 40초는 **컨테이너가 일어나는 시간**이지 대화를 처리하는 시간이 아니다.
 * 깨어난 뒤 실제 응답은 5~12초다. 그러니 앱을 여는 순간 아무 요청이나 한 번 보내
 * 미리 깨워두면, 사용자가 실제로 말할 때는 이미 준비돼 있다.
 *
 * ⚠️ 대화 메시지(`POST /api/chat`)를 미리 보내는 방식은 쓰지 않는다.
 *    백엔드에 대화 세션 상태가 생겨버려서, 사용자가 진짜로 말할 때
 *    "이미 목적지를 받은 상태"로 꼬인다. 부작용 없는 `/health` 로 충분하다.
 *
 * ⚠️ `mode: 'no-cors'` 인 이유 — AI 서버에 CORS 설정이 없어서 브라우저가 응답을
 *    읽지 못한다. 하지만 **요청 자체는 서버까지 도달**하고, 그것만으로 컨테이너는
 *    깨어난다. 우리는 응답이 필요 없으니 읽기를 포기하고 콘솔 오류만 없앤다.
 *    (GET 이라 프리플라이트도 없다)
 */

/** AI 서버 주소. 없으면 깨우기를 건너뛴다 — 없다고 앱이 멈추면 안 된다. */
const AI_URL = import.meta.env.VITE_AI_URL as string | undefined

/** 한 번 열린 화면에서 두 번 보내지 않는다 */
let started = false

/**
 * AI 서버를 깨운다. 여러 번 불러도 실제 요청은 한 번만 나간다.
 * 실패는 조용히 삼킨다 — 이건 미리 해두는 준비지, 사용자가 기다리는 일이 아니다.
 */
export function warmUpAi(): void {
  if (started || !AI_URL) return
  started = true
  fetch(`${AI_URL.replace(/\/$/, '')}/health`, {
    mode: 'no-cors',
    cache: 'no-store',
  }).catch(() => {
    // 못 보냈으면(인터넷이 아직 안 붙었다든지) 다음 기회에 다시 해본다.
    // 실패해도 사용자는 모르고, 최악의 경우 첫 발화의 자동 재시도가 받아준다.
    started = false
  })
}
