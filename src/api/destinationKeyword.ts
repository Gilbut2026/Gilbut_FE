/**
 * 발화에서 목적지 이름만 뽑아낸다 — AI 를 부르지 않고.
 *
 * 왜 만들었나(2026-08-19)
 * ─────────────────────────────────────────────────────────
 * 목적지 발화 한 번은 `POST /api/chat` → 백엔드 → AI(Gemini) 를 거친다. 그런데 AI 가
 * 하는 일은 「수원역 가고 싶어요」에서 「수원역」을 뽑는 것뿐이고, 그다음 장소 검색은
 * 백엔드가 TMAP 으로 한다.
 *
 * 그 한 번이 **6초에서 59초**가 걸린다(같은 문장 7회 실측: 6.2·7.6·25.9·25.9·41.5·
 * 41.7·58.7초). 백엔드 AI read timeout 이 30초라 절반 가까이가 타임아웃에 걸리고,
 * 재시도까지 실패하면 첫 발화가 통째로 죽는다. 대화 전체에서 AI 를 쓰는 곳은 여기
 * **한 번뿐**이라, 여기가 느리면 그게 곧 「앱이 느리다」가 된다.
 *
 * 그래서 흔한 말투는 우리가 직접 뽑는다. 뽑히면 프론트가 바로 장소를 검색해서
 * (출발지가 이미 쓰고 있는 그 길 — api/place 의 searchPlacesNear) 0.5초 만에 후보를
 * 보여준다. 못 뽑거나 검색 결과가 시원찮으면 **그때 AI 로 넘긴다.** 최악이어도 지금과
 * 같고, 흔한 경우는 50배 빠르다.
 *
 * 무엇을 안 하나
 * ─────────────────────────────────────────────────────────
 * 「수원역 근처 병원」처럼 **기준 장소가 섞인 말은 손대지 않는다.** 그건 「병원」을 찾되
 * 「수원역」 주변에서 찾으라는 뜻이라, 이름 하나를 뽑는 것으로는 안 된다. AI 가 할 일이다.
 *
 * 「어제 갔던 그 병원」 같은 것도 못 뽑는다. 못 뽑으면 null 을 주고 조용히 AI 로 간다 —
 * 여기서 억지로 뽑아내려다 엉뚱한 곳을 찾아주는 것이 제일 나쁘다.
 *
 * 마지막 판단은 검색이 한다
 * ─────────────────────────────────────────────────────────
 * 말끝을 걷어내는 규칙은 아무리 다듬어도 사람 말을 다 못 따라간다. 그래서 여기서는
 * **적당히 뽑고**, 그 단어로 검색해서 쓸 만한 후보가 안 나오면 부르는 쪽에서 AI 로
 * 넘기게 했다. 문법을 정교하게 맞히는 것보다 그 편이 훨씬 튼튼하다.
 */

/** 기준 장소가 섞인 말 — 이건 AI 가 풀어야 한다 */
const NEARBY = /(근처|주변|가까운|인근|가까이)/

/**
 * 말끝에 붙는 「가고 싶어요」류.
 *
 * 앞의 조사까지 함께 걷어낸다 — 「수원역으로 가고 싶어요」에서 「으로」가 남으면
 * 그 단어로는 아무것도 안 나온다.
 */
const INTENT_TAIL =
  /\s*(?:에|에서|으로|까지|를|을)?\s*(?:좀\s*)?(?:가고\s*싶(?:어요|어|습니다|다)|가려고(?:요|용)?|가려구요?|가야\s*(?:해요|돼요|한다|해)|가\s*주(?:세요|실래요)|가줘|가자|갈래(?:요)?|갈게(?:요)?|가는\s*(?:길|법)|어떻게\s*가(?:요|나요|죠)?|데려다\s*(?:주세요|줘)|찾아\s*(?:주세요|줘)|알려\s*(?:주세요|줘)|부탁(?:해요|합니다|해)|가요)\s*[.!?~]*$/

/** 「수원역이요」처럼 이름 뒤에 붙는 맺음말 */
const POLITE_TAIL = /\s*(?:이요|요|입니다|이에요|예요|이야|야)\s*[.!?~]*$/

/**
 * 「음… 수원역」처럼 앞에 붙는 군말.
 *
 * 뒤에 **공백이 있을 때만** 걷어낸다 — 그러지 않으면 「저수지」의 「저」를 먹는다.
 * 말줄임표가 붙는 일이 잦아서(음성 인식이 그렇게 적어준다) 그 사이의 문장부호는 넘긴다.
 */
const FILLER_HEAD = /^(?:음+|어+|아+|그+|저기|저|일단|우선)[…·.,!?~]*\s+/

/** 이름 뒤에 홀로 남은 조사. 「로」는 넣지 않는다 — 「효원로」의 「로」를 먹는다 */
const PARTICLE_TAIL = /(?:에서|에|으로|까지|를|을)$/

/** 이보다 짧으면 검색해봐야 아무거나 걸린다 */
const MIN_LENGTH = 2

/**
 * 발화에서 목적지 이름을 뽑는다. 우리가 다룰 말이 아니면 null — 부르는 쪽은 AI 로 간다.
 */
export function destinationKeyword(utterance: string): string | null {
  const raw = utterance.trim()
  if (!raw || NEARBY.test(raw)) return null

  let word = raw.replace(FILLER_HEAD, '').trim()

  // 말끝을 걷어낸다. 「가고 싶어요」를 떼면 「수원역이요」가 남는 식이라 두 번 본다
  const hadIntent = INTENT_TAIL.test(word)
  if (hadIntent) word = word.replace(INTENT_TAIL, '').trim()
  word = word.replace(POLITE_TAIL, '').trim()

  /*
   * 조사는 **말끝을 실제로 걷어냈을 때만** 뗀다.
   *
   * 「효원로」처럼 조사와 같은 글자로 끝나는 이름이 있다. 사용자가 이름만 말했을 때는
   * 그것이 이름 전체이므로 손대지 않는 것이 맞다.
   */
  if (hadIntent) {
    const cut = word.replace(PARTICLE_TAIL, '').trim()
    if (cut.length >= MIN_LENGTH) word = cut
  }

  return word.length >= MIN_LENGTH ? word : null
}
